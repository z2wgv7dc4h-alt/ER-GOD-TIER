// Ingest the EanNewton "ER NPC Levels" public Google Sheet into
// src/knowledge/npc-display.ts.
//
// SCOPE: player-model / cosmetic data only. The sheet holds the level and stat
// allocation an NPC has *as a player model* (character creation numbers), not
// combat absorb/resistance/poise/stance. It must never feed damage math.
// See docs/REVIEW.md and docs/SCOPE.md item 8.
//
// Usage: node scripts/ingest-npc-display.mjs
// Run from the repo root.

import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const SHEET_ID = '1jZokIy9PcX5UhUPcTe992aP21JiXL015sfP4sjYktu4'
const CSV_URL = `https://docs.google.com/spreadsheets/d/${SHEET_ID}/gviz/tq?tqx=out:csv&gid=0`

const here = dirname(fileURLToPath(import.meta.url))
const outPath = join(here, '..', 'src', 'knowledge', 'npc-display.ts')

function parseCsv(text) {
  const rows = []
  let row = []
  let field = ''
  let quoted = false
  for (let i = 0; i < text.length; i++) {
    const ch = text[i]
    if (quoted) {
      if (ch === '"') {
        if (text[i + 1] === '"') { field += '"'; i++ } else { quoted = false }
      } else field += ch
    } else if (ch === '"') quoted = true
    else if (ch === ',') { row.push(field); field = '' }
    else if (ch === '\n') { row.push(field); rows.push(row); row = []; field = '' }
    else if (ch === '\r') { /* skip */ }
    else field += ch
  }
  if (field.length || row.length) { row.push(field); rows.push(row) }
  return rows.filter((r) => r.some((c) => c.trim() !== ''))
}

const res = await fetch(CSV_URL)
if (!res.ok) throw new Error(`sheet fetch failed: ${res.status} ${res.statusText}`)
const csv = await res.text()
const rows = parseCsv(csv)
if (rows.length < 2) throw new Error('sheet had no data rows')

const header = rows[0].map((h) => h.trim())
const col = (name) => header.indexOf(name)
const iName = 0
const iLevel = col('Level')
const statCols = [
  ['vigor', col('VIG')],
  ['mind', col('MND')],
  ['endurance', col('END')],
  ['strength', col('STR')],
  ['dexterity', col('DEX')],
  ['intelligence', col('INT')],
  ['faith', col('FAI')],
  ['arcane', col('ARC')],
]
for (const [label, idx] of [['Level', iLevel], ...statCols.map(([n, i]) => [n, i])]) {
  if (idx < 0) throw new Error(`missing column ${label}`)
}

const cards = []
for (const row of rows.slice(1)) {
  const rawName = (row[iName] || '').trim()
  if (!rawName) continue
  const m = rawName.match(/^(\d+)\s*-\s*(.+)$/)
  const modelId = m ? m[1] : ''
  const name = (m ? m[2] : rawName).trim()
  if (!name) continue
  const stats = {}
  for (const [key, idx] of statCols) stats[key] = Number(row[idx]) || 0
  cards.push({ modelId, name, level: Number(row[iLevel]) || 0, stats })
}

const statObj = (s) =>
  `{ vigor: ${s.vigor}, mind: ${s.mind}, endurance: ${s.endurance}, strength: ${s.strength}, dexterity: ${s.dexterity}, intelligence: ${s.intelligence}, faith: ${s.faith}, arcane: ${s.arcane} }`

const body = cards
  .map(
    (c) =>
      `  { id: 'npc-display:${c.modelId}', modelId: '${c.modelId}', name: ${JSON.stringify(c.name)}, level: ${c.level}, stats: ${statObj(c.stats)} },`,
  )
  .join('\n')

const out = `/**
 * Player-model/cosmetic data only. NOT combat stats.
 * Do not use for absorb/resistance/damage calculations — see docs/REVIEW.md.
 *
 * Source: EanNewton "ER NPC Levels" public Google Sheet (player-model NPCs).
 * https://docs.google.com/spreadsheets/d/${SHEET_ID}/
 *
 * These are the level and stat allocation an NPC has as a player model
 * (character-creation numbers). They are display flavor for Codex cards, not
 * enemy combat params. The Build lab's "what should I hit this with" table is
 * ERDB NpcParam (absorb/stance/resistances/status) and is a separate source.
 *
 * Generated by scripts/ingest-npc-display.mjs — do not edit by hand.
 */

export type NpcDisplayStats = {
  vigor: number
  mind: number
  endurance: number
  strength: number
  dexterity: number
  intelligence: number
  faith: number
  arcane: number
}

export type NpcDisplayCard = {
  id: string
  /** Internal NPC row id from the sheet, e.g. "23000". */
  modelId: string
  name: string
  /** Player-model level, not a boss/enemy combat level. */
  level: number
  /** Player-model stat allocation (cosmetic reference only). */
  stats: NpcDisplayStats
}

export const npcDisplayCards: NpcDisplayCard[] = [
${body}
]

/** Cosmetic display lookup by (case-insensitive) name. Never for combat math. */
export function findNpcDisplay(name: string): NpcDisplayCard | undefined {
  const n = name.trim().toLowerCase()
  return npcDisplayCards.find((c) => c.name.toLowerCase() === n) ||
    npcDisplayCards.find((c) => c.name.toLowerCase().includes(n))
}
`

writeFileSync(outPath, out)
console.log(`wrote ${cards.length} player-model NPC display cards to ${outPath}`)
