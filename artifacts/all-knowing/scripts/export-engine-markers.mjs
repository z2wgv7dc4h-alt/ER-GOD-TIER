/**
 * Export the map engine's own named markers into our app data, so offline /
 * phone users get named pickups and "where to find X" without the live engine.
 *
 * The engine (vendor/elden-ring-map) is the canonical source — the user's
 * "EldenRingMap" Nexus pack is the same project and fully subsumed by it, so we
 * read the engine's `data/markers.json` + `data/items.json` here and nowhere else.
 *
 * Emits public/sourced/open/engine-markers.json:
 *   { source, graces:[{name,px,py}], markers:[{id,name,cat,px,py,master}],
 *     items:[{id,name,cat,map,px,py,near}] }
 *
 * `near` is the nearest Site of Grace by pixel distance in the engine's own
 * frame. Run after `build_markers.py` regenerates the engine data.
 *
 *   node scripts/export-engine-markers.mjs
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const DATA = path.join(ROOT, 'vendor', 'elden-ring-map', 'data')
const OUT = path.join(ROOT, 'public', 'sourced', 'open', 'engine-markers.json')

const markers = JSON.parse(fs.readFileSync(path.join(DATA, 'markers.json'), 'utf8')).markers ?? []
const items = JSON.parse(fs.readFileSync(path.join(DATA, 'items.json'), 'utf8')).markers ?? []

const en = (m) => (m.names && m.names.en) || ''

// The engine's own markers (graces, bosses, landmarks, poi, fragments). Our
// merged `ak:` rows are skipped — they are regenerated by map:merge.
const base = markers.filter((m) => !String(m.id).startsWith('ak:') && m.px != null && m.py != null && en(m))
const graces = base
  .filter((m) => m.cat === 'grace')
  .map((m) => ({ name: en(m), px: m.px, py: m.py }))
const worldMarkers = base.map((m) => ({
  id: m.id,
  name: en(m),
  cat: m.cat || 'poi',
  master: m.master || 'M00',
  px: Math.round(m.px * 10) / 10,
  py: Math.round(m.py * 10) / 10,
}))

function nearestGrace(px, py) {
  let best = ''
  let bestD = Infinity
  for (const g of graces) {
    const d = (g.px - px) ** 2 + (g.py - py) ** 2
    if (d < bestD) {
      bestD = d
      best = g.name
    }
  }
  return best
}

const rows = items
  .filter((m) => m.px != null && m.py != null && en(m))
  .map((m) => ({
    id: m.id,
    name: en(m),
    cat: m.cat || 'item',
    map: m.map || '',
    px: Math.round(m.px * 10) / 10,
    py: Math.round(m.py * 10) / 10,
    near: nearestGrace(m.px, m.py),
  }))
  .sort((a, b) => a.name.localeCompare(b.name))

fs.writeFileSync(
  OUT,
  JSON.stringify({ source: 'EldenRingMap engine (data/markers.json + data/items.json)', graces, markers: worldMarkers, items: rows }, null, 0),
)
console.log(`wrote ${OUT}`)
console.log(`  markers: ${worldMarkers.length}  graces: ${graces.length}  items: ${rows.length}  size: ${Math.round(fs.statSync(OUT).size / 1024)} KB`)
